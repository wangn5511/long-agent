def install_signal_handlers(base_module) -> None:
    def _handle_signal(signum, _frame):
        global STOP_REQUESTED
        if STOP_REQUESTED:
            base_module.log_status(
                f"[signal] Received signal {signum} again; waiting for active long videos to finish."
            )
            return
        STOP_REQUESTED = True
        base_module.log_status(
            f"[signal] Received signal {signum}; will stop scheduling new long videos "
            "and wait for currently running ones to finish."
        )

    signal.signal(signal.SIGINT, _handle_signal)
    signal.signal(signal.SIGTERM, _handle_signal)


def atomic_write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent))
    tmp = Path(tmp_path)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2, ensure_ascii=False)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    finally:
        if tmp.exists():
            tmp.unlink(missing_ok=True)


def build_global_category_payload(output_root: Path, categories: Sequence[str]) -> Tuple[dict, int]:
    annotations: "OrderedDict[str, Dict[str, object]]" = OrderedDict()
    manifest_paths = sorted(output_root.rglob("video_manifest.json"))
    for manifest_path in manifest_paths:
        with manifest_path.open("r", encoding="utf-8") as f:
            manifest = json.load(f)
        for sample_name, meta in manifest.get("clips", {}).items():
            annotations[str(sample_name)] = meta
    return {"categories": list(categories), "annotations": annotations}, len(manifest_paths)


def filter_final_crop_videos(
    base_module,
    args,
    crop_root: Path,
    video_rel_stem: str,
    clips_meta: Dict[str, dict],
    log_prefix: str,
) -> None:
    """Delete cropped clip videos that are not part of the final retained clips."""
    if not args.crop_first:
        return

    video_crop_dir = base_module.get_video_crop_dir(crop_root, video_rel_stem)
    if not video_crop_dir.exists():
        return

    keep_segment_stems = {
        str(meta.get("segment_stem"))
        for meta in clips_meta.values()
        if str(meta.get("segment_stem", "")).strip()
    }

    kept = 0
    removed = 0
    for clip_path in sorted(video_crop_dir.glob("*.mp4")):
        if clip_path.stem in keep_segment_stems:
            kept += 1
            continue
        clip_path.unlink(missing_ok=True)
        removed += 1

    base_module.log_status(
        f"{log_prefix} Final crop filter | kept={kept} removed={removed}"
    )


def get_video_media_stats(video_path: Path) -> Tuple[int, float]:
    try:
        import cv2  # type: ignore
    except ModuleNotFoundError as exc:
        raise ModuleNotFoundError("OpenCV (cv2) is required for long-video NONE mining.") from exc
    cap = cv2.VideoCapture(str(video_path))
    if not cap.isOpened():
        raise RuntimeError(f"Cannot open video: {video_path}")
    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    fps = float(cap.get(cv2.CAP_PROP_FPS))
    cap.release()
    if fps <= 0:
        fps = 30.0
    return total_frames, fps


def stable_video_seed(video_rel_stem: str, seed: int, salt: str) -> int:
    payload = f"{salt}::{video_rel_stem}::{int(seed)}".encode("utf-8")
    digest = hashlib.blake2b(payload, digest_size=8).digest()
    return int.from_bytes(digest, byteorder="big", signed=False)


def load_selected_long_videos(split_json: Path, split_name: str, source_kind: str, source_groups: Optional[Sequence[str]]) -> "OrderedDict[str, dict]":
    with split_json.open("r", encoding="utf-8") as f:
        data = json.load(f)
    videos = data.get("videos")
    if not isinstance(videos, dict):
        raise ValueError(f"Invalid split manifest format: {split_json}")
    allowed_groups = {str(item) for item in source_groups} if source_groups else None
    selected: "OrderedDict[str, dict]" = OrderedDict()
    for video_rel_stem, meta in sorted(videos.items()):
        if not isinstance(meta, dict):
            continue
        if str(meta.get("split", "")).strip().lower() != split_name.lower():
            continue
        if str(meta.get("source_kind", "")) != source_kind:
            continue
        source_group = meta.get("source_group")
        if allowed_groups is not None and str(source_group) not in allowed_groups:
            continue
        selected[str(video_rel_stem)] = dict(meta)
    return selected


def build_window_ranges(
    total_frames: int,
    fps: float,
    *,
    min_seconds: float,
    max_seconds: float,
    stride_seconds: float,
    min_frames: int,
    seed: int,
    video_rel_stem: str,
) -> List[Tuple[int, int]]:
    min_len = max(int(round(min_seconds * fps)), min_frames)
    max_len = max(min_len, int(round(max_seconds * fps)))
    stride = max(1, int(round(stride_seconds * fps)))
    rng = random.Random(stable_video_seed(video_rel_stem, seed, "window_ranges"))

    windows: List[Tuple[int, int]] = []
    start = 0
    while start + min_len <= total_frames:
        current_max_len = min(max_len, total_frames - start)
        clip_len = current_max_len if current_max_len <= min_len else rng.randint(min_len, current_max_len)
        end = start + clip_len - 1
        windows.append((start, end))
        start += stride
    return windows


def sample_candidate_ranges(
    candidate_ranges: Sequence[Tuple[int, int]],
    *,
    sample_size: int,
    seed: int,
    video_rel_stem: str,
) -> List[Tuple[int, int]]:
    windows = list(candidate_ranges)
    if sample_size <= 0 or len(windows) <= sample_size:
        return windows
    rng = random.Random(stable_video_seed(video_rel_stem, seed, "sample_candidate_ranges"))
    selected_indices = sorted(rng.sample(range(len(windows)), sample_size))
    return [windows[idx] for idx in selected_indices]


