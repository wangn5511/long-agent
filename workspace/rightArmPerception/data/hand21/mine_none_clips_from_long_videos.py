def build_single_clip_pipeline(cfg, compose_cls):
    pipeline_cfg = None
    if hasattr(cfg, "val_pipeline"):
        pipeline_cfg = json.loads(json.dumps(cfg.val_pipeline))
    elif hasattr(cfg, "test_pipeline"):
        pipeline_cfg = json.loads(json.dumps(cfg.test_pipeline))
    if pipeline_cfg is None:
        return None
    for item in pipeline_cfg:
        if item.get("type") == "UniformSampleFrames":
            item["num_clips"] = 1
            item["test_mode"] = True
    return compose_cls(pipeline_cfg)


def build_label_mapping(cfg) -> Dict[int, str]:
    class_mapping = getattr(cfg, "class_mapping", None)
    if class_mapping:
        return {int(k): str(v) for k, v in class_mapping.items()}
    num_classes = int(cfg.model.cls_head.num_classes)
    return {idx: str(idx) for idx in range(num_classes)}


def clip_json_to_fake_anno(clip_json: dict) -> dict:
    info = clip_json["info"]
    ann = clip_json["annotations"]
    width, height = info["resolution"]
    total_frames = int(info["num_frame"])
    num_keypoints = int(info["num_keypoints"])

    keypoint = np.zeros((1, total_frames, num_keypoints, 2), dtype=np.float32)
    keypoint_score = np.zeros((1, total_frames, num_keypoints), dtype=np.float32)
    for frame_ann in ann:
        frame_index = int(frame_ann["frame_index"])
        coords = np.asarray(frame_ann["keypoints"], dtype=np.float32)
        keypoint[0, frame_index] = coords[:, :2]
        keypoint_score[0, frame_index] = coords[:, 2]

    return {
        "frame_dict": "",
        "label": -1,
        "img_shape": (int(height), int(width)),
        "origin_shape": (int(height), int(width)),
        "start_index": 0,
        "modality": "Pose",
        "total_frames": total_frames,
        "keypoint": keypoint,
        "keypoint_score": keypoint_score,
    }


def recognizer_scores(result, label_mapping: Dict[int, str]) -> Tuple[str, float, Dict[str, float]]:
    pred_score = result.pred_score
    scores_raw = pred_score.tolist() if hasattr(pred_score, "tolist") else list(pred_score)
    scores = {label_mapping[idx]: float(score) for idx, score in enumerate(scores_raw)}
    best_idx = int(np.argmax(np.asarray(scores_raw)))
    return label_mapping.get(best_idx, str(best_idx)), float(scores_raw[best_idx]), scores


def mined_outputs_complete(base_module, args, output_root: Path, crop_root: Path, video_rel_stem: str, existing_manifest: dict) -> bool:
    manifest_path = base_module.get_video_manifest_path(output_root, video_rel_stem)
    if not manifest_path.exists():
        return False
    for meta in existing_manifest.get("clips", {}).values():
        rel_json = str(meta.get("relative_json_path", "")).strip()
        if not rel_json or not (output_root / rel_json).exists():
            return False
        if args.crop_first:
            segment_stem = str(meta.get("segment_stem", "")).strip()
            if not segment_stem:
                return False
            if not base_module.segment_crop_video_path(crop_root, video_rel_stem, segment_stem).exists():
                return False
    return True


