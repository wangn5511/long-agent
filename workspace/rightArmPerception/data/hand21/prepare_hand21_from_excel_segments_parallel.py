def _count_consecutive_missing_frames(clip_json: dict) -> int:
    """Return the longest run of all-zero skeleton frames in a prepared clip JSON.

    Mirrors the logic in evaluate_prepared_hand21_dataset.count_missing_frames_in_prepared_clip,
    but operates on the in-memory dict rather than a file, avoiding a disk round-trip.
    """
    longest_run = 0
    current_run = 0
    for frame in clip_json.get("annotations", []):
        keypoints = frame.get("keypoints", [])
        is_missing = bool(keypoints) and all(
            float(x) == 0.0 and float(y) == 0.0 and float(score) == 0.0
            for x, y, score in keypoints
        )
        if is_missing:
            current_run += 1
            if current_run > longest_run:
                longest_run = current_run
        else:
            current_run = 0
    return longest_run


def _max_other_track_coverage(
    anno: dict,
    main_track_id: int,
    start_frame: int,
    end_frame: int,
    is_segment_level: bool,
) -> float:
    """Return the highest coverage ratio of any non-primary hand track in the clip range.

    Mirrors the track-counting logic in evaluate_prepared_hand21_dataset.count_track_ids_in_segment.
    is_segment_level=True when anno covers exactly one cropped clip (crop_first mode).
    """
    from collections import Counter as _Counter
    segment_num_frames = 0
    track_frame_counts: "_Counter[int]" = _Counter()
    for frame in anno.get("frames", []):
        frame_idx = int(frame.get("frame_idx", -1))
        if not is_segment_level and (frame_idx < start_frame or frame_idx > end_frame):
            continue
        segment_num_frames += 1
        for hand in frame.get("hands", []):
            if "track_id" in hand:
                track_frame_counts[int(hand["track_id"])] += 1
    if segment_num_frames == 0:
        return 0.0
    max_other = 0.0
    for track_id, count in track_frame_counts.items():
        if track_id == main_track_id:
            continue
        ratio = count / segment_num_frames
        if ratio > max_other:
            max_other = ratio
    return max_other


def _is_missing_keypoints(keypoints: list) -> bool:
    """Return True when all keypoints in a frame are (0, 0, 0) — i.e. no detection."""
    return bool(keypoints) and all(
        float(x) == 0.0 and float(y) == 0.0 and float(score) == 0.0
        for x, y, score in keypoints
    )


def _repair_clip_gaps(clip_json: dict, max_gap: int) -> dict:
    """Fill internal missing-frame runs of length <= max_gap via linear interpolation.

    Ported from interpolate_prepared_hand21_short_gaps.repair_clip_json.
    Head/tail missing runs are left untouched (no anchor on one side).
    """
    annotations = clip_json.get("annotations", [])
    total = len(annotations)
    idx = 0
    while idx < total:
        if not _is_missing_keypoints(annotations[idx].get("keypoints", [])):
            idx += 1
            continue
        run_start = idx
        while idx < total and _is_missing_keypoints(annotations[idx].get("keypoints", [])):
            idx += 1
        run_end = idx  # exclusive
        gap_len = run_end - run_start
        has_prev = run_start > 0 and not _is_missing_keypoints(annotations[run_start - 1].get("keypoints", []))
        has_next = run_end < total and not _is_missing_keypoints(annotations[run_end].get("keypoints", []))
        if not has_prev or not has_next or gap_len > max_gap:
            continue
        prev_kpts = annotations[run_start - 1]["keypoints"]
        next_kpts = annotations[run_end]["keypoints"]
        for offset in range(gap_len):
            alpha = float(offset + 1) / float(gap_len + 1)
            annotations[run_start + offset]["keypoints"] = [
                [
                    (1.0 - alpha) * float(prev_kpts[j][0]) + alpha * float(next_kpts[j][0]),
                    (1.0 - alpha) * float(prev_kpts[j][1]) + alpha * float(next_kpts[j][1]),
                    (1.0 - alpha) * float(prev_kpts[j][2]) + alpha * float(next_kpts[j][2]),
                ]
                for j in range(len(prev_kpts))
            ]
    clip_json["annotations"] = annotations
    return clip_json


def _recompute_clip_valid_stats(clip_json: dict) -> Dict[str, float]:
    """Recompute valid_frames / valid_ratio / mean_hand_score after gap interpolation."""
    annotations = clip_json.get("annotations", [])
    num_frames = len(annotations)
    valid_frames = 0
    score_sum = 0.0
    for frame in annotations:
        kpts = frame.get("keypoints", [])
        if not _is_missing_keypoints(kpts):
            valid_frames += 1
            score_sum += float(kpts[0][2]) if kpts else 0.0
    valid_ratio = float(valid_frames / num_frames) if num_frames > 0 else 0.0
    mean_hand_score = float(score_sum / valid_frames) if valid_frames > 0 else 0.0
    return {
        "valid_frames": float(valid_frames),
        "valid_ratio": valid_ratio,
        "mean_hand_score": mean_hand_score,
    }


def process_single_video_job(job: dict) -> dict:
    base = load_base_module()
    args = SimpleNamespace(**job["args"])
    categories = list(job["categories"])
    label_to_id = {label: idx for idx, label in enumerate(categories)}
    video_rel_stem = str(job["video_rel_stem"])
    video_segments = list(job["video_segments"])
    source_video_path = Path(str(video_segments[0]["video_path"]))
    kpts_root = Path(args.kpts_root)
    crop_root = Path(args.crop_root)
    output_root = Path(args.output_root)
    video_crop_dir = base.get_video_crop_dir(crop_root, video_rel_stem)
    log_prefix = str(job["log_prefix"])

    current_signature = base.build_video_signature(
        args=args,
        source_video_path=source_video_path,
        video_rel_stem=video_rel_stem,
        segments=video_segments,
        categories=categories,
    )
    manifest_path = base.get_video_manifest_path(output_root, video_rel_stem)
    existing_manifest = base.load_json_if_exists(manifest_path)
    if (
        args.skip_existing_videos
        and existing_manifest is not None
        and existing_manifest.get("signature") == current_signature
        and base.video_outputs_complete(
            args=args,
            output_root=output_root,
            kpts_root=kpts_root,
            crop_root=crop_root,
            video_rel_stem=video_rel_stem,
            segments=video_segments,
        )
    ):
        filter_final_crop_videos(
            base_module=base,
            args=args,
            crop_root=crop_root,
            video_rel_stem=video_rel_stem,
            clips_meta=existing_manifest.get("clips", {}),
            log_prefix=log_prefix,
        )
        base.log_status(f"{log_prefix} Skip unchanged video with {len(video_segments)} segments")
        return {
            "video_rel_stem": video_rel_stem,
            "processed": False,
            "skipped": True,
            "rebuilt": False,
            "written": int(existing_manifest.get("num_samples_written", 0)),
            "skipped_short": int(existing_manifest.get("num_segments_skipped_short", 0)),
            "skipped_low_valid": int(existing_manifest.get("num_segments_skipped_low_valid", 0)),
            "crop_written": int(existing_manifest.get("num_segments_cropped", 0)),
            "crop_skipped": int(existing_manifest.get("num_segments_crop_skipped", 0)),
            "skipped_low_quality": int(existing_manifest.get("num_segments_skipped_low_quality", 0)),
        }

    video_output_dir = base.get_video_output_dir(output_root, video_rel_stem)
    video_clips_dir = base.get_video_clips_dir(output_root, video_rel_stem)
    video_kpts_dir = base.get_video_kpts_dir(kpts_root, video_rel_stem)

    rebuilt = False
    if existing_manifest is not None or video_output_dir.exists() or video_kpts_dir.exists() or (
        args.crop_first and video_crop_dir.exists()
    ):
        rebuilt = True
        base.log_status(f"{log_prefix} Rebuild outputs for this video because inputs or config changed")

    base.remove_path_if_exists(video_output_dir)
    if args.crop_first:
        base.remove_path_if_exists(video_crop_dir)
    if not args.skip_extract:
        base.remove_path_if_exists(video_kpts_dir)
    video_clips_dir.mkdir(parents=True, exist_ok=True)

    extractor_module = None if args.skip_extract else base.load_extractor_module()
    video_crop_stats = {
        "num_segments_cropped": 0,
        "num_segments_crop_skipped": 0,
    }
    if args.crop_first:
        video_crop_stats = base.crop_source_video_segments(
            segments=video_segments,
            video_rel_stem=video_rel_stem,
            crop_root=crop_root,
            log_prefix=log_prefix,
        )
        if extractor_module is not None:
            base.extract_video_clips(
                module=extractor_module,
                args=args,
                video_crop_dir=video_crop_dir,
                video_kpts_dir=video_kpts_dir,
                log_prefix=log_prefix,
            )
    elif extractor_module is not None:
        base.extract_single_source_video(
            module=extractor_module,
            args=args,
            source_video_path=source_video_path,
            video_kpts_dir=video_kpts_dir,
            log_prefix=log_prefix,
        )

    video_clip_meta: "OrderedDict[str, Dict[str, object]]" = OrderedDict()
    video_written = 0
    video_skipped_short = 0
    video_skipped_low_valid = 0
    video_skipped_low_quality = 0
    total_video_segments = len(video_segments)
    base.log_status(f"{log_prefix} Build hand21 JSON clips from {total_video_segments} segments")

    source_video_annotations = None
    if not args.crop_first:
        source_anno_path = video_kpts_dir / "annotations.json"
        if not source_anno_path.exists():
            raise FileNotFoundError(f"{log_prefix} Missing MediaPipe annotations: {source_anno_path}")
        with source_anno_path.open("r", encoding="utf-8") as f:
            source_video_annotations = json.load(f)

    for seg_idx, segment in enumerate(video_segments, start=1):
        segment_stem = str(segment["segment_stem"])
        current = seg_idx

        if segment.get("skip_reason"):
            video_skipped_short += 1
            if base.should_report_progress(current, total_video_segments):
                base.log_status(
                    f"{log_prefix} Clip progress {base.format_progress(current, total_video_segments)} | "
                    f"written={video_written} skipped_short={video_skipped_short} "
                    f"skipped_low_valid={video_skipped_low_valid}"
                )
            continue

        if args.crop_first:
            anno_path = base.segment_kpts_annotations_path(kpts_root, video_rel_stem, segment_stem)
            if not anno_path.exists():
                raise FileNotFoundError(f"{log_prefix} Missing MediaPipe annotations for clip: {anno_path}")
            with anno_path.open("r", encoding="utf-8") as f:
                annotations = json.load(f)
            total_frames = int(annotations.get("total_frames", 0))
            start_frame = 0
            end_frame = total_frames - 1
            source_start_frame = int(segment.get("crop_source_start_frame", segment["start_frame"]))
            source_end_frame = int(segment.get("crop_source_end_frame", segment["end_frame"]))
            kpts_source = f"{video_rel_stem}/{segment_stem}"
        else:
            annotations = source_video_annotations
            total_frames = int(annotations.get("total_frames", 0))
            start_frame = max(0, int(segment["start_frame"]))
            end_frame = min(total_frames - 1, int(segment["end_frame"]))
            source_start_frame = start_frame
            source_end_frame = end_frame
            kpts_source = video_rel_stem

        clip_frames = end_frame - start_frame + 1
        if clip_frames < args.min_frames:
            video_skipped_short += 1
            if base.should_report_progress(current, total_video_segments):
                base.log_status(
                    f"{log_prefix} Clip progress {base.format_progress(current, total_video_segments)} | "
                    f"written={video_written} skipped_short={video_skipped_short} "
                    f"skipped_low_valid={video_skipped_low_valid}"
                )
            continue

        try:
            track_id = base.select_segment_track(
                annotations=annotations,
                start_frame=start_frame,
                end_frame=end_frame,
                preferred_handedness=args.handedness,
                explicit_track_id=args.track_id,
            )
        except ValueError:
            video_skipped_low_valid += 1
            if base.should_report_progress(current, total_video_segments):
                base.log_status(
                    f"{log_prefix} Clip progress {base.format_progress(current, total_video_segments)} | "
                    f"written={video_written} skipped_short={video_skipped_short} "
                    f"skipped_low_valid={video_skipped_low_valid}"
                )
            continue

        valid_stats = base.compute_clip_valid_stats(
            annotations=annotations,
            track_id=track_id,
            start_frame=start_frame,
            end_frame=end_frame,
        )
        if (
            int(valid_stats["valid_frames"]) < args.min_valid_frames
            or float(valid_stats["valid_ratio"]) < args.min_valid_ratio
        ):
            video_skipped_low_valid += 1
            if base.should_report_progress(current, total_video_segments):
                base.log_status(
                    f"{log_prefix} Clip progress {base.format_progress(current, total_video_segments)} | "
                    f"written={video_written} skipped_short={video_skipped_short} "
                    f"skipped_low_valid={video_skipped_low_valid}"
                )
            continue

        label = str(segment["label"])
        sample_name = str(segment["sample_name"])
        clip_json = base.build_clip_json(
            annotations=annotations,
            track_id=track_id,
            start_frame=start_frame,
            end_frame=end_frame,
            sample_name=sample_name,
            category_id=label_to_id[label],
            use_smooth=args.use_smooth,
            joint_score_source=args.joint_score_source,
        )

        # --- Quality filter (replaces separate evaluate + interpolate scripts) ---
        if not args.skip_quality_filter:
            # Criterion 1: valid_ratio
            if float(valid_stats["valid_ratio"]) < args.low_quality_valid_ratio:
                video_skipped_low_quality += 1
                if base.should_report_progress(current, total_video_segments):
                    base.log_status(
                        f"{log_prefix} Clip progress {base.format_progress(current, total_video_segments)} | "
                        f"written={video_written} skipped_short={video_skipped_short} "
                        f"skipped_low_valid={video_skipped_low_valid} skipped_low_quality={video_skipped_low_quality}"
                    )
                continue
            # Criterion 2: consecutive missing frames
            longest_missing = _count_consecutive_missing_frames(clip_json)
            if longest_missing > args.max_consecutive_missing_threshold:
                video_skipped_low_quality += 1
                if base.should_report_progress(current, total_video_segments):
                    base.log_status(
                        f"{log_prefix} Clip progress {base.format_progress(current, total_video_segments)} | "
                        f"written={video_written} skipped_short={video_skipped_short} "
                        f"skipped_low_valid={video_skipped_low_valid} skipped_low_quality={video_skipped_low_quality}"
                    )
                continue
            # Criterion 3: other-track interference
            is_seg_level = args.crop_first
            other_track = _max_other_track_coverage(
                annotations, track_id, start_frame, end_frame, is_seg_level
            )
            if other_track > args.other_track_coverage_threshold:
                video_skipped_low_quality += 1
                if base.should_report_progress(current, total_video_segments):
                    base.log_status(
                        f"{log_prefix} Clip progress {base.format_progress(current, total_video_segments)} | "
                        f"written={video_written} skipped_short={video_skipped_short} "
                        f"skipped_low_valid={video_skipped_low_valid} skipped_low_quality={video_skipped_low_quality}"
                    )
                continue
            # Gap interpolation: fill short internal missing runs
            clip_json = _repair_clip_gaps(clip_json, args.max_interpolation_gap)
            # Recompute valid stats after interpolation (valid_ratio may have improved)
            post_stats = _recompute_clip_valid_stats(clip_json)
            valid_stats = {**valid_stats, **post_stats}

        out_path = base.segment_clip_json_path(output_root, video_rel_stem, segment_stem)
        atomic_write_json(out_path, clip_json)

        sample_meta = {
            "category_id": label_to_id[label],
            "label": label,
            "source_video": video_rel_stem,
            "source_video_path": str(source_video_path),
            "segment_stem": segment_stem,
            "relative_json_path": str(out_path.relative_to(output_root)),
            "kpts_source": kpts_source,
            "track_id": track_id,
            "start_frame": source_start_frame,
            "end_frame": source_end_frame,
            "num_frames": clip_frames,
            "valid_frames": int(valid_stats["valid_frames"]),
            "valid_ratio": float(valid_stats["valid_ratio"]),
            "mean_hand_score": float(valid_stats["mean_hand_score"]),
            "row_idx": int(segment["row_idx"]),
            "annotation_split": None
            if segment.get("annotation_split") is None
            else str(segment.get("annotation_split")),
        }
        video_clip_meta[sample_name] = sample_meta
        video_written += 1
        if base.should_report_progress(current, total_video_segments):
            base.log_status(
                f"{log_prefix} Clip progress {base.format_progress(current, total_video_segments)} | "
                f"written={video_written} skipped_short={video_skipped_short} "
                f"skipped_low_valid={video_skipped_low_valid} skipped_low_quality={video_skipped_low_quality}"
            )

    video_manifest = {
        "source_video_rel_stem": video_rel_stem,
        "source_video_path": str(source_video_path),
        "signature": current_signature,
        "crop_first": bool(args.crop_first),
        "num_segments_input": len(video_segments),
        "num_samples_written": video_written,
        "num_segments_skipped_short": video_skipped_short,
        "num_segments_skipped_low_valid": video_skipped_low_valid,
        "num_segments_skipped_low_quality": video_skipped_low_quality,
        "num_segments_cropped": int(video_crop_stats["num_segments_cropped"]),
        "num_segments_crop_skipped": int(video_crop_stats["num_segments_crop_skipped"]),
        "clips": video_clip_meta,
        "updated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    atomic_write_json(manifest_path, video_manifest)
    filter_final_crop_videos(
        base_module=base,
        args=args,
        crop_root=crop_root,
        video_rel_stem=video_rel_stem,
        clips_meta=video_clip_meta,
        log_prefix=log_prefix,
    )

    base.log_status(
        f"{log_prefix} Finished | written={video_written} skipped_short={video_skipped_short} "
        f"skipped_low_valid={video_skipped_low_valid} skipped_low_quality={video_skipped_low_quality}"
    )
    return {
        "video_rel_stem": video_rel_stem,
        "processed": True,
        "skipped": False,
        "rebuilt": rebuilt,
        "written": video_written,
        "skipped_short": video_skipped_short,
        "skipped_low_valid": video_skipped_low_valid,
        "skipped_low_quality": video_skipped_low_quality,
        "crop_written": int(video_crop_stats["num_segments_cropped"]),
        "crop_skipped": int(video_crop_stats["num_segments_crop_skipped"]),
    }


def run_jobs(
    base_module,
    args,
    categories: Sequence[str],
    segments_by_video,
) -> Dict[str, int]:
    worker_args = make_worker_args(args)
    totals = {
        "processed_videos": 0,
        "skipped_videos": 0,
        "rebuilt_videos": 0,
        "written": 0,
        "skipped_short": 0,
        "skipped_low_valid": 0,
        "skipped_low_quality": 0,
        "crop_written": 0,
        "crop_skipped": 0,
    }
    video_items = list(segments_by_video.items())
    total_videos = len(video_items)
    if total_videos == 0:
        return totals

    def apply_result(result: dict) -> None:
        if result["processed"]:
            totals["processed_videos"] += 1
        if result["skipped"]:
            totals["skipped_videos"] += 1
        if result["rebuilt"]:
            totals["rebuilt_videos"] += 1
        totals["written"] += int(result["written"])
        totals["skipped_short"] += int(result["skipped_short"])
        totals["skipped_low_valid"] += int(result["skipped_low_valid"])
        totals["crop_written"] += int(result["crop_written"])
        totals["crop_skipped"] += int(result["crop_skipped"])
        totals["skipped_low_quality"] += int(result.get("skipped_low_quality", 0))

    if args.jobs == 1:
        for idx, (video_rel_stem, video_segments) in enumerate(video_items, start=1):
            if STOP_REQUESTED:
                break
            result = process_single_video_job(
                {
                    "args": worker_args,
                    "categories": list(categories),
                    "video_rel_stem": video_rel_stem,
                    "video_segments": video_segments,
                    "log_prefix": f"[video {idx}/{total_videos}] {video_rel_stem} |",
                }
            )
            apply_result(result)
        return totals

    mp_context = multiprocessing.get_context("spawn")
    max_workers = min(args.jobs, total_videos)
    with concurrent.futures.ProcessPoolExecutor(
        max_workers=max_workers,
        mp_context=mp_context,
    ) as executor:
        future_to_index: Dict[concurrent.futures.Future, int] = {}
        next_index = 0

        def submit_one(index: int) -> None:
            video_rel_stem, video_segments = video_items[index]
            future = executor.submit(
                process_single_video_job,
                {
                    "args": worker_args,
                    "categories": list(categories),
                    "video_rel_stem": video_rel_stem,
                    "video_segments": video_segments,
                    "log_prefix": f"[video {index + 1}/{total_videos}] {video_rel_stem} |",
                },
            )
            future_to_index[future] = index

        while next_index < total_videos and len(future_to_index) < max_workers and not STOP_REQUESTED:
            submit_one(next_index)
            next_index += 1

        while future_to_index:
            done, _pending = concurrent.futures.wait(
                future_to_index.keys(),
                return_when=concurrent.futures.FIRST_COMPLETED,
            )
            for future in done:
                index = future_to_index.pop(future)
                result = future.result()
                apply_result(result)
                if not STOP_REQUESTED and next_index < total_videos:
                    submit_one(next_index)
                    next_index += 1

            if STOP_REQUESTED:
                for future in list(future_to_index):
                    if future.cancel():
                        future_to_index.pop(future, None)

    return totals


def main() -> None:
    base = load_base_module()
    install_signal_handlers(base)
    args = parse_args()
    kpts_root = args.kpts_root or args.output_root.parent / f"{args.output_root.name}_video_kpts"
    crop_root = args.crop_root or args.output_root.parent / f"{args.output_root.name}_segments_videos"
    args.kpts_root = kpts_root
    args.crop_root = crop_root

    existing_categories = None
    if args.categories is None:
        existing_categories = maybe_load_existing_categories(args.output_root)
        if existing_categories:
            args.categories = existing_categories

    base.log_status(
        f"[start] video_root={args.video_root} | annotation_file={args.annotation_file} | "
        f"output_root={args.output_root} | crop_first={args.crop_first} | "
        f"skip_existing_videos={args.skip_existing_videos} | jobs={args.jobs} | "
        f"video_subdirs={args.video_subdirs or 'ALL'} | "
        f"video_list_txt={args.video_list_txt or 'NONE'} | "
        f"video_split_json={args.video_split_json or 'NONE'} | "
        f"split_name={args.split_name or 'NONE'}"
    )
    if existing_categories:
        base.log_status(
            f"[categories] Reuse existing category order from {args.output_root / 'category_annotation.json'}"
        )
    if args.jobs > 1:
        prewarm_model_if_needed(base, args)

    video_index = base.build_video_index(args.video_root)
    base.log_status(f"[scan] Indexed {len(video_index)} video lookup keys under {args.video_root}")

    if args.annotation_format == "compact_4col":
        rows = base.load_compact_4col_rows(args.annotation_file, args.sheet_name)
    else:
        rows = base.load_tabular_rows(args.annotation_file, args.sheet_name)
        if args.annotation_format == "auto":
            required = {args.video_col, args.label_col, args.start_col, args.end_col}
            header = set(rows[0].keys()) if rows else set()
            if not required.issubset(header):
                rows = base.load_compact_4col_rows(args.annotation_file, args.sheet_name)
                args.annotation_format = "compact_4col"
            else:
                args.annotation_format = "table"
    base.log_status(f"[load] Loaded {len(rows)} annotation rows with format={args.annotation_format}")

    segments, categories, missing_video_rows, invalid_frame_rows = base.collect_segments(args, rows, video_index)
    if not segments:
        missing_keys = sorted({str(item["video_key"]) for item in missing_video_rows})
        invalid_keys = sorted({str(item["video_key"]) for item in invalid_frame_rows})
        preview_keys = missing_keys + [key for key in invalid_keys if key not in missing_keys]
        preview = ", ".join(preview_keys[:10])
        if len(preview_keys) > 10:
            preview += ", ..."
        raise FileNotFoundError(
            "No valid annotation rows remained after video/frame validation. "
            f"Affected video keys: {preview or 'none'}"
        )
    selected_segments = filter_segments_by_subdirs(segments, args.video_root, args.video_subdirs)
    if args.video_subdirs:
        base.log_status(
            f"[filter] Selected {len(selected_segments)} of {len(segments)} valid segments under {args.video_subdirs}"
        )
    if not selected_segments and args.video_subdirs:
        base.log_status("[filter] No valid segments matched the requested subdirectories")

    selected_videos: Optional[set[str]] = None
    if args.video_list_txt is not None:
        selected_videos = load_selected_videos_from_txt(args.video_list_txt)
        base.log_status(
            f"[filter] Loaded {len(selected_videos)} source videos from {args.video_list_txt}"
        )
    elif args.video_split_json is not None:
        selected_videos = load_selected_videos_from_split_json(args.video_split_json, args.split_name)
        base.log_status(
            f"[filter] Loaded {len(selected_videos)} source videos for split={args.split_name} "
            f"from {args.video_split_json}"
        )

    selected_segments = filter_segments_by_selected_videos(selected_segments, selected_videos)
    if selected_videos is not None:
        base.log_status(
            f"[filter] Retained {len(selected_segments)} valid segments after source-video selection"
        )
        if not selected_segments:
            base.log_status("[filter] No valid segments matched the requested source-video selection")

    if not selected_segments:
        raise ValueError("No valid segments remained after applying the requested source-video filters.")

    base.assign_stable_segment_names(selected_segments)
    segments_by_video = base.group_segments_by_source_video(selected_segments)
    base.log_status(
        f"[group] Prepared {len(selected_segments)} selected segments across {len(segments_by_video)} source videos"
    )

    args.output_root.mkdir(parents=True, exist_ok=True)
    kpts_root.mkdir(parents=True, exist_ok=True)
    if args.crop_first:
        crop_root.mkdir(parents=True, exist_ok=True)

    totals = run_jobs(
        base_module=base,
        args=args,
        categories=categories,
        segments_by_video=segments_by_video,
    )

    category_payload, manifest_count = build_global_category_payload(args.output_root, categories)
    atomic_write_json(args.output_root / "category_annotation.json", category_payload)

    summary = {
        "video_root": str(args.video_root),
        "annotation_file": str(args.annotation_file),
        "kpts_root": str(kpts_root),
        "crop_first": args.crop_first,
        "crop_root": str(crop_root) if args.crop_first else None,
        "output_root": str(args.output_root),
        "categories": categories,
        "video_subdirs": args.video_subdirs,
        "video_list_txt": str(args.video_list_txt) if args.video_list_txt else None,
        "video_split_json": str(args.video_split_json) if args.video_split_json else None,
        "split_name": args.split_name,
        "jobs": args.jobs,
        "stop_requested": STOP_REQUESTED,
        "num_source_videos_selected": len(segments_by_video),
        "num_source_videos_processed": totals["processed_videos"],
        "num_source_videos_skipped": totals["skipped_videos"],
        "num_source_videos_rebuilt": totals["rebuilt_videos"],
        "num_segments_selected": len(selected_segments),
        "num_segments_written": totals["written"],
        "num_segments_skipped_short": totals["skipped_short"],
        "num_segments_skipped_low_valid": totals["skipped_low_valid"],
        "num_segments_skipped_low_quality": totals["skipped_low_quality"],
        "quality_filter_enabled": not args.skip_quality_filter,
        "low_quality_valid_ratio": args.low_quality_valid_ratio,
        "other_track_coverage_threshold": args.other_track_coverage_threshold,
        "max_consecutive_missing_threshold": args.max_consecutive_missing_threshold,
        "max_interpolation_gap": args.max_interpolation_gap,
        "num_segments_cropped": totals["crop_written"],
        "num_segments_crop_skipped": totals["crop_skipped"],
        "num_annotation_rows_missing_video": len(missing_video_rows),
        "missing_video_rows": missing_video_rows,
        "num_annotation_rows_invalid_frame": len(invalid_frame_rows),
        "invalid_frame_rows": invalid_frame_rows,
        "annotation_format": args.annotation_format,
        "use_smooth": args.use_smooth,
        "joint_score_source": args.joint_score_source,
        "handedness": args.handedness,
        "track_id": args.track_id,
        "min_valid_frames": args.min_valid_frames,
        "min_valid_ratio": args.min_valid_ratio,
        "skip_existing_videos": args.skip_existing_videos,
        "prepare_mode": args.prepare_mode,
        "num_existing_video_manifests_after_run": manifest_count,
        "num_existing_samples_after_run": len(category_payload["annotations"]),
        "updated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    atomic_write_json(args.output_root / "prepare_summary.json", summary)

    base.log_status(f"[done] Saved dataset root: {args.output_root}")
    base.log_status(f"[done] Saved category annotation: {args.output_root / 'category_annotation.json'}")
    base.log_status(f"[done] Saved prepare summary: {args.output_root / 'prepare_summary.json'}")
    base.log_status(f"[done] Selected source videos: {len(segments_by_video)}")
    base.log_status(f"[done] Source videos processed: {totals['processed_videos']}")
    base.log_status(f"[done] Source videos skipped: {totals['skipped_videos']}")
    base.log_status(f"[done] Source videos rebuilt: {totals['rebuilt_videos']}")
    base.log_status(f"[done] Segments written: {totals['written']}")
    base.log_status(f"[done] Segments skipped (too short): {totals['skipped_short']}")
    base.log_status(f"[done] Segments skipped (low valid coverage): {totals['skipped_low_valid']}")
    base.log_status(f"[done] Segments skipped (low quality / filtered): {totals['skipped_low_quality']}")
    base.log_status(f"[done] Annotation rows skipped (video not found): {len(missing_video_rows)}")
    base.log_status(f"[done] Annotation rows skipped (invalid frame range): {len(invalid_frame_rows)}")
    base.log_status(f"[done] Categories: {categories}")


if __name__ == "__main__":
    main()
