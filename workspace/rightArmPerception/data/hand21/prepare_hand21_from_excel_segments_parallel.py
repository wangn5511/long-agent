#!/usr/bin/env python3
"""Parallel incremental wrapper for prepare_hand21_from_excel_segments.py.

This script keeps the original prepare script untouched and adds:
1. Folder-scoped processing via ``--video-subdirs``.
2. Per-source-video multiprocessing via ``--jobs``.
3. Graceful parent-process stop handling: stop scheduling new videos after
   SIGINT/SIGTERM and wait for running videos to finish.
4. Atomic JSON writes for clip/manifests/global metadata created here.

The per-video processing logic intentionally mirrors the original script so
existing outputs and skip/rebuild behavior stay compatible.
"""

